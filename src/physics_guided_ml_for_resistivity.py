def radar_plot(metrics_df, savepath):
    cols = ["R2","RMSE","MAE"]
    # normalizers
    r2_min, r2_max = metrics_df["R2"].min(), metrics_df["R2"].max()
    rmse_min, rmse_max = metrics_df["RMSE"].min(), metrics_df["RMSE"].max()
    mae_min, mae_max = metrics_df["MAE"].min(), metrics_df["MAE"].max()

    def norm_higher(x, lo, hi): return 0.5 if hi==lo else (x-lo)/(hi-lo)
    def norm_lower(x, lo, hi):  return 0.5 if hi==lo else 1.0 - (x-lo)/(hi-lo)

    scores=[]
    for _, row in metrics_df.iterrows():
        scores.append([
            norm_higher(row["R2"],  r2_min,  r2_max),
            norm_lower (row["RMSE"],rmse_min,rmse_max),
            norm_lower (row["MAE"], mae_min, mae_max)
        ])
    labels = metrics_df["model"].tolist()
    theta = np.linspace(0, 2*np.pi, len(cols), endpoint=False)
    fig = plt.figure(figsize=(6.4,6.4))
    ax = plt.subplot(111, polar=True)
    for lab, sc in zip(labels, scores):
        vals = np.r_[sc, sc[0]]
        th   = np.r_[theta, theta[0]]
        ax.plot(th, vals, lw=2, label=lab)
        ax.fill(th, vals, alpha=0.15)
    ax.set_thetagrids(theta * 180/np.pi, cols)
    ax.set_ylim(0, 1.0)
    ax.set_title("Base model comparison (normalized radar)")
    ax.legend(loc="upper right", bbox_to_anchor=(1.25, 1.12))
    fig.tight_layout(); fig.savefig(savepath, dpi=300); plt.close(fig)

