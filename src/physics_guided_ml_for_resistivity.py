def fit_copula(X):
    qt = QuantileTransformer(n_quantiles=min(100, len(X)), output_distribution="normal", random_state=42)
    Z = qt.fit_transform(X)
    mu = Z.mean(0)
    cov = np.cov(Z.T) + 1e-6*np.eye(Z.shape[1])
    return qt, mu, cov

def sample_copula(qt, mu, cov, n):
    Zs = np.random.multivariate_normal(mu, cov, size=n)
    return qt.inverse_transform(Zs)

def local_residual_noise(X_tr, y_tr, k=7):
    sc = StandardScaler().fit(X_tr)
    Z = sc.transform(X_tr)
    base = build_xgb(dict(n_estimators=1200, max_depth=6, learning_rate=0.05,
                          subsample=0.9, colsample_bytree=0.9))
    base.fit(X_tr, np.log10(y_tr))
    res = np.log10(y_tr) - base.predict(X_tr)
    knn = KNeighborsRegressor(n_neighbors=min(max(3, k), max(2, len(Z)-1)), weights="distance")
    knn.fit(Z, res**2 + 1e-8)
    rng = np.random.default_rng(123)
    def draw(x_new):
        v = float(knn.predict(sc.transform(x_new.reshape(1,-1)))[0])
        return rng.normal(0.0, math.sqrt(max(v, 1e-10)))
    return draw

def build_augmented_features(X, *, comp_override=None, element_names=None, proc=None,
                             shap_series=None, max_shap=6):
    Xaug = X.copy()
    # (A) process polys/interactions
    if proc:
        for p in proc:
            if p in Xaug.columns:
                Xaug[f"{p}^2"] = Xaug[p]**2
        if len(proc) >= 2:
            for a,b in combinations(proc, 2):
                if a in Xaug.columns and b in Xaug.columns:
                    Xaug[f"{a}*{b}"] = Xaug[a]*Xaug[b]
    # (B) SHAP-informed simple nonlinearities
    if shap_series is not None:
        top = [f for f in shap_series.index if f in Xaug.columns][:max_shap]
        for c in top:
            Xaug[f"{c}^2"] = Xaug[c]**2
        for a,b in combinations(top, 2):
            Xaug[f"{a}*{b}"] = Xaug[a]*Xaug[b]
    # (C) composition-derived features
    comp = None
    if element_names:
        if comp_override is not None:
            comp = np.asarray(comp_override, dtype=float)
        elif set(element_names).issubset(set(Xaug.columns)):
            comp = Xaug[element_names].to_numpy(dtype=float)
    if comp is not None:
        s = comp.sum(axis=1, keepdims=True) + 1e-12
        p = comp / s
        H  = -(p * (np.log(p + 1e-12))).sum(axis=1)
        HH = (p**2).sum(axis=1)
        Xaug["comp_entropy"]     = H
        Xaug["comp_herfindahl"]  = HH
        idx_map = {el:i for i,el in enumerate(element_names)}
        for (a,b) in list(combinations(element_names, 2))[:3]:
            ia, ib = idx_map[a], idx_map[b]
            Xaug[f"{a}/{b}"] = comp[:, ia] / (comp[:, ib] + 1e-9)
    return Xaug

