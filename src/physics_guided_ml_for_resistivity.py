def model_default():
    base = Pipeline([
        ("scaler", RobustScaler()),
        ("regressor", GradientBoostingRegressor(
            random_state=42, n_estimators=600, max_depth=3,
            learning_rate=0.10, subsample=0.7
        ))
    ])
    # Log1p on target often stabilizes resistivity
    return TransformedTargetRegressor(regressor=base, func=np.log1p, inverse_func=np.expm1)

def oof_predictions(X, y, n_splits=5, rs=42, quantiles=(0.1,0.5,0.9)):
    kf = KFold(n_splits=n_splits, shuffle=True, random_state=rs)
    yhat = np.zeros_like(y, dtype=float)
    yq = {q: np.zeros_like(y, dtype=float) for q in quantiles}
    for tr, te in kf.split(X, y):
        Xtr, Xte = X.iloc[tr], X.iloc[te]
        ytr = y.iloc[tr]

        m = model_default()
        m.fit(Xtr, ytr)
        yhat[te] = m.predict(Xte)

        # quantile models for predictive intervals
        for q in quantiles:
            g = GradientBoostingRegressor(
                loss="quantile", alpha=q, n_estimators=600, max_depth=3,
                learning_rate=0.05, subsample=1.0, random_state=rs
            )
            pipe = Pipeline([("scaler", RobustScaler()), ("regressor", g)])
            pipe.fit(Xtr, ytr)
            yq[q][te] = pipe.predict(Xte)
    return yhat, yq

