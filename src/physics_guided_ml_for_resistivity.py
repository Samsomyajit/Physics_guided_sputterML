def ale_1d(model, pre, X_df, feature, K=20):
    """Simple ALE approximation on raw feature."""
    x = X_df[feature].to_numpy()
    qs = np.quantile(x, np.linspace(0,1,K+1))
    xs = 0.5*(qs[:-1]+qs[1:])
    eff=[]
    for a,b in zip(qs[:-1], qs[1:]):
        idx = (x>=a)&(x<b)
        if idx.sum()==0: eff.append(0); continue
        X0 = X_df.loc[idx].copy()
        X1, X2 = X0.copy(), X0.copy()
        X1[feature] = a; X2[feature] = b
        P1 = model.predict(pre.transform(X1))
        P2 = model.predict(pre.transform(X2))
        eff.append(float(np.mean(P2-P1)))
    ale = np.cumsum(eff) - np.mean(np.cumsum(eff))
    return xs, ale

