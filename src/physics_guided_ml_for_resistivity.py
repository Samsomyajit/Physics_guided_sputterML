def cv_r2_with_early_stopping(model_builder, params, X, y, folds):
    X = to_f32(X); y = np.asarray(y)
    r2s=[]
    for tr, te in folds:
        Xtr, Xte = X[tr], X[te]
        ytr, yte = y[tr], y[te]
        model = model_builder(params)
        kind = getattr(model, "_kind", "")
        if kind=="xgb":
            model.set_params(early_stopping_rounds=80)
            model.fit(Xtr, ytr, eval_set=[(Xte, yte)], verbose=False)
        elif kind=="lgbm":
            cbs=[lgb.early_stopping(stopping_rounds=80, verbose=False),
                 lgb.log_evaluation(period=0)]
            model.fit(Xtr, ytr, eval_set=[(Xte, yte)], eval_metric="l2", callbacks=cbs)
        elif kind=="cat":
            model.set_params(early_stopping_rounds=100)
            model.fit(Xtr, ytr, eval_set=(Xte, yte), verbose=False, use_best_model=True)
        else:
            model.fit(Xtr, ytr)
        pred = model.predict(Xte)
        r2s.append(r2_score(yte, pred))
    return float(np.mean(r2s))

