# ---------- 3) Ceilings ----------
def nearest_neighbor_ceiling(Zs, y, q=0.30):
    nbrs = NearestNeighbors(n_neighbors=2, metric="euclidean").fit(Zs)
    dists, idxs = nbrs.kneighbors(Zs)
    pair_idx = idxs[:, 1]
    pair_dist = dists[:, 1]
    thr = np.quantile(pair_dist, q)
    m = pair_dist <= thr
    if m.sum() < 3:
        return np.nan, np.nan, 0
    y1, y2 = y[m], y[pair_idx[m]]
    ss_res = np.sum((y1 - y2)**2)
    ss_tot = np.sum((y1 - y1.mean())**2)
    r2 = 1 - ss_res/ss_tot if ss_tot > 0 else np.nan
    noise_var = 0.5 * np.median((y1 - y2)**2)
    r2_bound = 1 - (noise_var / np.var(y, ddof=0)) if np.var(y) > 0 else np.nan
    return r2, r2_bound, int(m.sum())

def knn_loocv_ceiling(Zs, y):
    n = len(Zs)
    k = min(5, max(2, n // 10))
    if k < 2: return np.nan, k
    loo = LeaveOneOut()
    knn = KNeighborsRegressor(n_neighbors=k, weights="distance")
    yhat = cross_val_predict(knn, Zs, y, cv=loo, n_jobs=-1)
    return r2_score(y, yhat), k

def icc_1_1(groups, y):
    if not groups: return np.nan
    m = np.mean([len(g) for g in groups])
    ybar = np.mean(y)
    ss_between = sum([len(g) * (np.mean(y[g]) - ybar)**2 for g in groups])
    ss_within  = sum([np.sum((y[g] - np.mean(y[g]))**2) for g in groups])
    k = len(groups)
    MSB = ss_between / (k - 1) if k > 1 else 0.0
    MSW = ss_within  / (sum(len(g) for g in groups) - k)
    denom = MSB + (m - 1) * MSW
    return (MSB - MSW) / denom if denom > 0 else np.nan

def duplicate_icc(Zs, y, eps=0.10):
    # cluster "practical duplicates": max-abs(Standardized Δ) <= eps in all features
    D = cdist(Zs, Zs, metric="chebyshev")
    groups = []
    used = np.zeros(len(Zs), dtype=bool)
    for i in range(len(Zs)):
        if used[i]: continue
        grp = np.where(D[i] <= eps)[0]
        if len(grp) >= 2:
            groups.append(grp)
            used[grp] = True
    return icc_1_1(groups, y), len(groups), eps

