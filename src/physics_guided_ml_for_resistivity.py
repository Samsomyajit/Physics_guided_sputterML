def plot_pca_loadings_box(df_features: pd.DataFrame, n_components=6,
                          font_axis=22, font_tick=20, font_legend=20,
                          xtick_rotation=55):
    """
    df_features: numeric features (rows=samples, cols=features)
    Returns: (loadings_df, fitted_pca)
    """
    # === PCA ===
    X  = df_features.values.astype(float)
    Xs = StandardScaler().fit_transform(X)
    k  = min(n_components, min(Xs.shape))
    pca = PCA(n_components=k).fit(Xs)
    load = pd.DataFrame(pca.components_.T, index=df_features.columns,
                        columns=[f"PC{i+1}" for i in range(k)])
    long = load.reset_index(names="Feature").melt("Feature", var_name="PC", value_name="Loading")

    # === Plot (no auto legend; we add one at the bottom) ===
    sns.set_style("ticks")
    palette = sns.color_palette("tab10", n_colors=k)
    g = sns.catplot(
        data=long, x="Feature", y="Loading", hue="PC",
        kind="bar", height=7.8, aspect=2.4, palette=palette,
        legend=False  # <- prevent seaborn's legend
    )
    ax = g.axes.flat[0]

    # Axis labels & ticks (bigger)
    ax.set_title("")                      # no title
    ax.set_xlabel("Characteristic variables", fontsize=font_axis)
    ax.set_ylabel("Load value",            fontsize=font_axis)
    ax.tick_params(axis="x", labelsize=font_tick)
    ax.tick_params(axis="y", labelsize=font_tick)
    ax.set_xticklabels(ax.get_xticklabels(), rotation=xtick_rotation, ha="right")

    # Zero line
    ax.axhline(0, lw=1.6, color="black")

    # Boxed spines
    for sp in ax.spines.values():
        sp.set_visible(True); sp.set_linewidth(1.6)

    # Remove any stray legend that might appear (belt & suspenders)
    if ax.get_legend() is not None:
        ax.get_legend().remove()
    if hasattr(g, "_legend") and g._legend is not None:
        g._legend.remove()

    # Bottom, horizontal legend we control
    handles = [Patch(facecolor=palette[i], edgecolor='none', label=f"PC{i+1}") for i in range(k)]
    leg = g.fig.legend(handles=handles, title="PC",
                       loc="lower center", bbox_to_anchor=(0.5, -0.06),
                       ncol=min(k, 6), frameon=True, prop={"size": font_legend})
    if leg.get_title() is not None:
        leg.get_title().set_fontsize(font_legend)

    # Room for legend & rotated x-labels
    g.fig.subplots_adjust(bottom=0.25, top=0.98, left=0.06, right=0.995)
    return load, pca

