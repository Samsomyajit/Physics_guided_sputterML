def _spearman_np(y_true, y_pred):
    ry = pd.Series(y_true).rank(method="average").to_numpy()
    rp = pd.Series(y_pred).rank(method="average").to_numpy()
    return float(np.corrcoef(ry, rp)[0,1])

def _metrics_linear(y_true_lin, y_pred_lin):
    y_true_lin = np.asarray(y_true_lin, float); y_pred_lin = np.asarray(y_pred_lin, float)
    mse = mean_squared_error(y_true_lin, y_pred_lin)
    rmse = float(np.sqrt(mse))
    mean_y = float(np.mean(y_true_lin))
    var_y  = float(np.var(y_true_lin, ddof=1)) if len(y_true_lin) > 1 else np.nan
    return dict(
        R2=float(r2_score(y_true_lin, y_pred_lin)),
        MSE=float(mse),
        RMSE=rmse,
        MAE=float(mean_absolute_error(y_true_lin, y_pred_lin)),
        MedianAE=float(np.median(np.abs(y_true_lin - y_pred_lin))),
        MAPE=float(np.mean(np.abs((y_true_lin - y_pred_lin)/np.maximum(np.abs(y_true_lin),1e-12))) * 100.0),
        PearsonR=float(np.corrcoef(y_true_lin, y_pred_lin)[0,1]),
        SpearmanR=_spearman_np(y_true_lin, y_pred_lin),
        NMSE=(mse/var_y) if np.isfinite(var_y) and var_y>0 else np.nan,
        NMAE=(mean_absolute_error(y_true_lin, y_pred_lin)/mean_y) if np.isfinite(mean_y) and mean_y>0 else np.nan,
    )

