def plot_pso_composition_bars(
    csv_path,
    out_path="Figure_PSO_Composition.pdf",
    comp_candidates=("In","Ga","Sn","Zn"),
    pred_candidates=("pred_resistivity","prediction","yhat","pred","resistivity_pred"),
    rank_by_ascending=True,   # True ⇒ low resistivity = better (top)
    topk=20,
    dpi=300
):
    # ---------- load ----------
    df = pd.read_csv(csv_path)

    # ---------- column resolution (case/space tolerant) ----------
    def norm(s): return s.lower().replace(" ", "").replace("_","")
    canon = {norm(c): c for c in df.columns}

    def pick_one(cands):
        for c in cands:
            if norm(c) in canon: return canon[norm(c)]
        for k,v in canon.items():                # substring fallback
            if any(norm(c) in k for c in cands): return v
        return None

    comp_cols = [pick_one((c,)) for c in comp_candidates if pick_one((c,)) is not None]
    if not comp_cols:
        raise ValueError("No composition columns found (expected some of In/Ga/Sn/Zn).")

    pred_col = pick_one(pred_candidates)
    if pred_col is None:
        # fallback: any column that looks like "pred*" and mentions "resist"
        preds = [c for c in df.columns if ("pred" in norm(c) and "resist" in norm(c))] \
             or [c for c in df.columns if "pred" in norm(c)]
        if preds: pred_col = preds[0]
    if pred_col is None:
        raise ValueError("No prediction column found.")

    # ---------- tidy ----------
    dat = df.copy()
    comp = dat[comp_cols].astype(float)
    if comp.max(numeric_only=True).max() <= 1.01:  # convert to %
        comp = comp * 100.0
    dat = pd.concat([comp, dat[[pred_col]].astype(float)], axis=1).dropna()

    # rank + keep topk
    dat = dat.sort_values(pred_col, ascending=rank_by_ascending).head(topk).reset_index(drop=True)
    n = len(dat)
    y = np.arange(n)[::-1]                        # top rank on top

    # ---------- style ----------
    sns.set_theme(context="talk", style="whitegrid")
    plt.rcParams.update({"font.family": "DejaVu Serif"})   # Times-like fallback

    # ---------- plot ----------
    fig, ax = plt.subplots(figsize=(8.2, 7), dpi=dpi)
    palette = sns.color_palette("colorblind", len(comp_cols))

    left = np.zeros(n)
    for i, c in enumerate(comp_cols):
        ax.barh(y, dat[c].values, left=left, height=0.7,
                color=palette[i], label=c)
        left += dat[c].values

    ax.set_xlim(0, 100)
    ax.set_xlabel("Composition (%)", labelpad=8)
    ax.set_yticks(y)
    ax.set_yticklabels([f"{i+1:02d}" for i in range(n)], fontsize=11)
    ax.set_ylabel("PSO rank (best at top)")
    ax.invert_yaxis()
    for spine in ("right","top"): ax.spines[spine].set_visible(False)

    # horizontal legend, bottom center
    ax.legend(frameon=False, ncol=len(comp_cols),
                loc="lower center", bbox_to_anchor=(0.5, -0.25),
              handlelength=1.2, handletextpad=0.5, columnspacing=1.0)

    fig.savefig(out_path, bbox_inches="tight", dpi=dpi)
    fig.savefig(out_path.replace(".pdf",".png"), bbox_inches="tight", dpi=dpi)
    print("Saved:", out_path)

