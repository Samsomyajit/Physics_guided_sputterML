def fit_with_es(est_name, base_params, Xtr, ytr, Xva, yva):
    if est_name == "xgb":
        params = dict(base_params)
        # XGBoost alias safety
        if "gamma" in params and "min_split_loss" not in params:
            params["min_split_loss"] = params.pop("gamma")

        # Build model; place eval_metric on estimator (not in fit)
        try:
            model = XGBRegressor(
                device=("cuda" if USE_CUDA else "cpu"),
                random_state=SEED,
                n_jobs=-1,
                objective="reg:squarederror",
                eval_metric="rmse",
                **params
            )
        except TypeError:
            model = XGBRegressor(
                device=("cuda" if USE_CUDA else "cpu"),
                random_state=SEED,
                n_jobs=-1,
                objective="reg:squarederror",
                **params
            )
            try: model.set_params(eval_metric="rmse")
            except Exception: pass

        es_rounds = 80
        fit_kwargs = {"eval_set": [(Xva, yva)]}

        # Try in order: callbacks → early_stopping_rounds (fit) → estimator param → no-ES
        if _fit_accepts_kwarg(model, "fit", "callbacks"):
            try:
                es_cb = xgb.callback.EarlyStopping(rounds=es_rounds, save_best=True, maximize=False)
            except Exception:
                es_cb = xgb.callback.EarlyStopping(rounds=es_rounds)
            fit_kwargs["callbacks"] = [es_cb]
        elif _fit_accepts_kwarg(model, "fit", "early_stopping_rounds"):
            fit_kwargs["early_stopping_rounds"] = es_rounds
        else:
            try: model.set_params(early_stopping_rounds=es_rounds)
            except Exception: pass  # final fallback: train without ES

        # Avoid passing eval_metric into fit() for 3.x
        model.fit(Xtr, ytr, **fit_kwargs)
        return model

    elif est_name == "lgbm":
        model = _make_lgbm_regressor(random_state=SEED, **base_params)
        es_rounds = 80
        if callable(lgb_early_stopping):
            model.fit(Xtr, ytr, eval_set=[(Xva, yva)],
                      callbacks=[lgb_early_stopping(stopping_rounds=es_rounds, verbose=False)])
        else:
            # Older API accepts early_stopping_rounds in fit
            model.fit(Xtr, ytr, eval_set=[(Xva, yva)], early_stopping_rounds=es_rounds, verbose=False)
        return model

    elif est_name == "cat":
        # --- CatBoost: normalize params so 'iterations' is passed once ---
        params_cb = dict(base_params)
        if "n_estimators" in params_cb and "iterations" not in params_cb:
            params_cb["iterations"] = params_cb.pop("n_estimators")
        else:
            params_cb.pop("n_estimators", None)  # remove alias if both are present

        task = "GPU" if USE_CUDA else "CPU"
        model = CatBoostRegressor(
            random_seed=SEED,
            task_type=task,
            loss_function="RMSE",
            verbose=False,
            **params_cb  # includes 'iterations' only once
        )
        model.fit(
            Xtr, ytr,
            eval_set=Pool(Xva, yva),
            early_stopping_rounds=100,
            verbose=False
        )
        return model

    else:
        raise ValueError("unknown estimator")

