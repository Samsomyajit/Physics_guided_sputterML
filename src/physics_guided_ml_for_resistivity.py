def smooth_response_contour(
    csv_path,
    temp_candidates=("sintering temperature","sintering_temperature","Tsint","T_sinter","temperature"),
    hold_candidates=("holding time","holding_time","thold","hold_time","time"),
    pred_candidates=("pred_resistivity","prediction","yhat","pred","resistivity_pred",
                     "pred_xgb","pred_lgbm","pred_cat"),
    grid_Nx=160, grid_Ny=120, gamma="auto", alpha=1e-2, levels=14,
    cmap="Spectral", dpi=300, out_path="Fig_TempHold_SmoothContour.pdf"
):
    df = pd.read_csv(csv_path)
    nrm = lambda s: s.lower().replace(" ","").replace("_","")
    canon = {nrm(c): c for c in df.columns}
    def pick(cands):
        for c in cands:
            if nrm(c) in canon: return canon[nrm(c)]
        for k,v in canon.items():
            if any(nrm(c) in k for c in cands): return v
        return None

    Tcol, Hcol = pick(temp_candidates), pick(hold_candidates)
    Pcols = [pick((c,)) for c in pred_candidates if pick((c,)) is not None]
    if not (Tcol and Hcol) or not Pcols: raise ValueError("Missing T/H or prediction columns.")
