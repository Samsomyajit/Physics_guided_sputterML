def cv_score_est(est_name, params, X, y):
    scores=[]
    for tr, te in cv.split(np.arange(len(y)), y):
        # inner split for ES
        X_tr, y_tr = X[tr], y[tr]
        X_te, y_te = X[te], y[te]
        X_tr2, X_va, y_tr2, y_va = train_test_split(X_tr, y_tr, test_size=0.2, random_state=SEED)
        model = fit_with_es(est_name, params, X_tr2, y_tr2, X_va, y_va)
        pred_log = model.predict(X_te)
        pred     = 10**pred_log  # score in linear space
        scores.append(r2_score(10**y_te, pred))
    return float(np.mean(scores))

