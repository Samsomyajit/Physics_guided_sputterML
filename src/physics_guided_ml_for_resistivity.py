def _fit_accepts_kwarg(obj, mname, kw):
    import inspect
    try:
        sig = inspect.signature(getattr(obj, mname))
        if kw in sig.parameters: return True
        return any(p.kind == p.VAR_KEYWORD for p in sig.parameters.values())
    except Exception:
        return False

def fit_es(est, Xtr, ytr, Xva, yva):
    if isinstance(est, XGBRegressor):
        es_rounds = 80
        fit_kwargs = {"eval_set":[(Xva, yva)]}
        if _fit_accepts_kwarg(est, "fit", "callbacks"):
            try:
                cb = xgb.callback.EarlyStopping(rounds=es_rounds, save_best=True, maximize=False)
            except Exception:
                cb = xgb.callback.EarlyStopping(rounds=es_rounds)
            fit_kwargs["callbacks"] = [cb]
        elif _fit_accepts_kwarg(est, "fit", "early_stopping_rounds"):
            fit_kwargs["early_stopping_rounds"] = es_rounds
        else:
            try: est.set_params(early_stopping_rounds=es_rounds)
            except: pass
        est.fit(Xtr, ytr, **fit_kwargs)
        return est
    if isinstance(est, LGBMRegressor):
        es_rounds = 80
        try:
            from lightgbm.callback import early_stopping as lgb_es
            est.fit(Xtr, ytr, eval_set=[(Xva, yva)], callbacks=[lgb_es(stopping_rounds=es_rounds, verbose=False)])
        except Exception:
            est.fit(Xtr, ytr, eval_set=[(Xva, yva)], early_stopping_rounds=es_rounds, verbose=False)
