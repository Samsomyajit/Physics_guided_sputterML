def nested_oof_predictions(X, y_t, outer_splits=OUTER_K, seed=SEED_MAIN+1):
    """True nested OOF on transformed target; returns y_pred_t and list of best params (per fold)."""
    from copy import deepcopy
    outer = KFold(outer_splits, shuffle=True, random_state=seed)
    y_pred_t = np.empty_like(y_t, dtype=float)
    best_params = []
    for tr, te in outer.split(X, y_t):
        s = make_search(seed)
        s.fit(X.iloc[tr], y_t[tr])
        y_pred_t[te] = s.predict(X.iloc[te])
        best_params.append(deepcopy(getattr(s, "best_params_", {})))
    return y_pred_t, best_params

def nested_calibrated_oof(X, y_raw, t_modeB="log10", outer_splits=OUTER_K, seed=SEED_MAIN+2):
    """Nested isotonic calibration; Duan smearing if log10. Returns OOF predictions on raw scale."""
    y_t = np.log10(y_raw) if t_modeB=="log10" else y_raw
    outer = KFold(outer_splits, shuffle=True, random_state=seed)
    y_pred_raw = np.empty_like(y_raw, dtype=float)

    for tr, te in outer.split(X, y_t):
        s = make_search(seed)
        s.fit(X.iloc[tr], y_t[tr])
        p_tr_t = s.predict(X.iloc[tr])
        p_te_t = s.predict(X.iloc[te])
        if t_modeB=="log10":
            # Duan smearing on outer-train
            e = y_t[tr] - p_tr_t
            smear = float(np.mean(10**e))
            iso = IsotonicRegression(out_of_bounds="clip").fit(p_tr_t, y_t[tr])
            p_te_t_iso = iso.predict(p_te_t)
            y_pred_raw[te] = (10**p_te_t_iso) * smear
        else:
            iso = IsotonicRegression(out_of_bounds="clip").fit(p_tr_t, y_t[tr])
            y_pred_raw[te] = iso.predict(p_te_t)
    return y_pred_raw

def bootstrap_ci_r2(y_true, y_pred, B=B_BOOT, seed=SEED_MAIN+3):
    rng = np.random.default_rng(seed)
    idx = np.arange(len(y_true)); r2s=[]
    for _ in range(B):
        b = rng.choice(idx, size=len(idx), replace=True)
        yt, yp = y_true[b], y_pred[b]
        ss_res = ((yt-yp)**2).sum(); ss_tot = ((yt-yt.mean())**2).sum()
        r2s.append(1 - ss_res/ss_tot if ss_tot>0 else np.nan)
    r2s = np.array(r2s, float)
    return np.nanpercentile(r2s, [2.5, 50, 97.5])

def permutation_nested_r2_fast(X, y_t, n_perm=NPERM, outer_splits=OUTER_K, seed=SEED_MAIN+4):
    """Y-scrambling on transformed target; nested OOF each time (3-fold inner in search)."""
    rng = np.random.default_rng(seed)
    scores=[]
    for b in range(n_perm):
        y_perm = shuffle(y_t, random_state=int(rng.integers(0, 1e9)))
        y_perm_pred, _ = nested_oof_predictions(X, y_perm, outer_splits=outer_splits, seed=seed+b+1)
        scores.append(r2_score(y_perm, y_perm_pred))
    return np.array(scores)

def ridge_baseline_stats(X, y_t):
    """Linear baseline (RidgeCV) for comparison and AIC/BIC on full-data fit."""
    pipe = Pipeline([
        ("pre", make_preprocessor()),
        ("ridge", RidgeCV(alphas=np.logspace(-3,3,31)))
    ])
    # 5-fold CV on transformed target
    cv = KFold(5, shuffle=True, random_state=77)
    oof = np.empty_like(y_t, dtype=float)
    for tr, te in cv.split(X, y_t):
        p = Pipeline([("pre", make_preprocessor()), ("ridge", RidgeCV(alphas=np.logspace(-3,3,31)))])
        p.fit(X.iloc[tr], y_t[tr])
        oof[te] = p.predict(X.iloc[te])
    r2_cv = r2_score(y_t, oof)

    # AIC/BIC on full-data fit
    fit_full = pipe.fit(X, y_t)
    Phi = fit_full.named_steps["pre"].transform(X)   # (n,p) design after preprocessing
    yhat = fit_full.predict(X)
    n, p = Phi.shape
    rss = float(np.sum((y_t - yhat)**2))
    sigma2 = rss / n
    loglik = -0.5*n*(np.log(2*np.pi*sigma2) + 1)
    k = p + 1  # coefficients + intercept
    AIC = 2*k - 2*loglik
    BIC = math.log(n)*k - 2*loglik
    return r2_cv, p, n, p, AIC, BIC

