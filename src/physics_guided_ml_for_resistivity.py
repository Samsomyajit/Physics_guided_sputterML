feat_cols = (ELEMENTS or []) + (proc or []) + [c for c in df_clean.columns if c in PHYS_SET]
df_used = df_clean[[TARGET] + feat_cols].dropna().copy()
X_full = df_used[feat_cols].astype(float)
y_full = df_used[TARGET].to_numpy(float)
assert np.all(y_full > 0), "This script uses log10(target). Found non-positive values."

# normalize compositions to 100 or 1 if element columns exist
if ELEMENTS:
    comp = X_full[ELEMENTS].to_numpy(float)
    s = comp.sum(axis=1, keepdims=True) + 1e-12
    tgt = 100.0 if 80 <= float(np.median(s)) <= 120 else 1.0
    X_full.loc[:, ELEMENTS] = comp * (tgt / s)

# bounds + integer-ish process constraints
mins = X_full.min().to_numpy(float)
maxs = X_full.max().to_numpy(float)
INTISH = set([c for c in (proc or []) if c in X_full.columns and
              (pd.api.types.is_integer_dtype(X_full[c]) or
               np.allclose(X_full[c], np.round(X_full[c]), atol=1e-6))])

# ---------- Utils ----------
def make_xgb(seed=7, **over):
    """CPU-only XGB; works for xgboost>=1.7 and >=2.0."""
    p = dict(
        n_estimators=1200, max_depth=6, learning_rate=0.05,
        subsample=0.9, colsample_bytree=0.9,
        tree_method="hist", random_state=seed, n_jobs=-1, verbosity=0
    )
    try:
        major = int(xgb_ver.split(".")[0])
        if major >= 2:
            p["device"] = "cpu"  # xgboost>=2 uses 'device' instead of predictor
    except: pass
    p.update(over)
    return XGBRegressor(**p)

def fit_copula(X):
    qt = QuantileTransformer(n_quantiles=min(100, len(X)), output_distribution="normal", random_state=42)
    Z = qt.fit_transform(X)
    mu = Z.mean(0)
    cov = np.cov(Z.T) + 1e-6*np.eye(Z.shape[1])
    return qt, mu, cov

def sample_copula(qt, mu, cov, n):
    Zs = np.random.multivariate_normal(mu, cov, size=n)
    return qt.inverse_transform(Zs)

def enforce_constraints(Xs, cols):
    Xs = np.clip(Xs, mins, maxs)
    if ELEMENTS:
        idx = [cols.index(c) for c in ELEMENTS]
        s = Xs[:, idx].sum(1, keepdims=True) + 1e-12
        tgt = 100.0 if 80 <= float(np.median(s)) <= 120 else 1.0
        Xs[:, idx] *= (tgt / s)
    for c in INTISH:
        j = cols.index(c)
        Xs[:, j] = np.round(Xs[:, j])
    return Xs

def local_residual_noise(X_tr, y_tr, k=7):
    sc = StandardScaler().fit(X_tr)
    Z = sc.transform(X_tr)
    # quick base model on log10 target
    base = make_xgb(seed=101)
    base.fit(X_tr, np.log10(y_tr))
    res = np.log10(y_tr) - base.predict(X_tr)
    knn = KNeighborsRegressor(n_neighbors=min(max(3, k), max(2, len(Z)-1)), weights="distance")
    knn.fit(Z, res**2 + 1e-8)
    rng = np.random.default_rng(123)
    def draw(x_new):
        v = float(knn.predict(sc.transform(x_new.reshape(1,-1)))[0])
        return rng.normal(0.0, math.sqrt(max(v, 1e-10)))
    return draw

def augment_train(X_tr, y_tr, *, mult=2.0, by_cluster=True, cols=None):
    """Copula sampling + composition/process constraints + heteroscedastic noise (in log space)."""
    if cols is None:
        cols = list(range(X_tr.shape[1]))
    n_syn = int(len(X_tr) * mult)
    Xsyn = None
    if by_cluster and len(X_tr) >= 30:
        k = min(3, max(2, len(X_tr)//25))
        sc = StandardScaler().fit(X_tr)
        Z = sc.transform(X_tr)
        gmm = GaussianMixture(n_components=k, covariance_type="full", random_state=42).fit(Z)
        lab = gmm.predict(Z)
        blocks = []
        for L in range(k):
            idx = np.where(lab==L)[0]
            if len(idx) < 8:
                continue
            qt, mu, cov = fit_copula(X_tr[idx])
            nL = max(4, int(n_syn * len(idx) / len(X_tr)))
            blocks.append(sample_copula(qt, mu, cov, nL))
        if blocks:
            Xsyn = np.vstack(blocks)
    if Xsyn is None or (hasattr(Xsyn, "size") and Xsyn.size == 0):
        qt, mu, cov = fit_copula(X_tr)
        Xsyn = sample_copula(qt, mu, cov, n_syn)
    # constraints
    Xsyn = enforce_constraints(Xsyn, cols=list(cols))
    # label with current model (log space) + local heteroscedastic noise
    base = make_xgb(seed=123)
    base.fit(X_tr, np.log10(y_tr))
    y_log_hat = base.predict(Xsyn)
    draw = local_residual_noise(X_tr, y_tr, k=7)
    y_log_noisy = y_log_hat + np.array([draw(x) for x in Xsyn])
    # back to raw
    y_syn = np.clip(10**y_log_noisy, 1e-12, None)
    X_aug = np.vstack([X_tr, Xsyn])
    y_aug = np.hstack([y_tr, y_syn])
    return X_aug, y_aug

def metrics(y_true, y_pred):
    return dict(
        R2 = r2_score(y_true, y_pred),
        RMSE = math.sqrt(mean_squared_error(y_true, y_pred)),
        MAE = mean_absolute_error(y_true, y_pred)
    )

# ---------- Nested CV: inner picks augmentation multiplier; outer yields OOF ----------
SEED_OUTER = 2025
outer = KFold(5, shuffle=True, random_state=SEED_OUTER)

y_oof_raw = np.zeros_like(y_full, dtype=float)
y_oof_pre_iso = np.zeros_like(y_full, dtype=float)  # raw before calibration
chosen_mult = []
fold_rows = []

mult_grid = [2.0, 3.0]   # from your sweep

for fold, (tr, te) in enumerate(outer.split(X_full, y_full), 1):
    Xtr = X_full.iloc[tr].to_numpy(float)
    ytr = y_full[tr]
    Xte = X_full.iloc[te].to_numpy(float)
    yte = y_full[te]

    # ----- inner CV to pick best multiplier -----
    inner = KFold(3, shuffle=True, random_state=fold+10)
    mult_scores = []
    for mult in mult_grid:
        r2s=[]
        for tri, vei in inner.split(Xtr, ytr):
            Xi, yi = Xtr[tri], ytr[tri]
            Vi, yi_val = Xtr[vei], ytr[vei]
            Xaug, yaug = augment_train(Xi, yi, mult=mult, by_cluster=True, cols=X_full.columns.tolist())
            m = make_xgb(seed=77+fold)
            m.fit(Xaug, np.log10(yaug))
            y_val_pred = np.clip(10**m.predict(Vi), 1e-12, None)
            r2s.append(r2_score(yi_val, y_val_pred))
        mult_scores.append((mult, float(np.mean(r2s))))
    best_mult = sorted(mult_scores, key=lambda t: t[1], reverse=True)[0][0]
    chosen_mult.append(best_mult)

    # ----- train on augmented full-train with best_mult -----
    Xaug, yaug = augment_train(Xtr, ytr, mult=best_mult, by_cluster=True, cols=X_full.columns.tolist())
    model = make_xgb(seed=99+fold, n_estimators=1400, max_depth=6)
    model.fit(Xaug, np.log10(yaug))

    # OOF prediction (pre-calibration)
    y_hat_raw = np.clip(10**model.predict(Xte), 1e-12, None)
    y_oof_raw[te] = y_hat_raw
    y_oof_pre_iso[te] = y_hat_raw

    fold_rows.append({
        "fold": fold, "chosen_mult": best_mult, **metrics(yte, y_hat_raw)
    })

df_folds = pd.DataFrame(fold_rows)
