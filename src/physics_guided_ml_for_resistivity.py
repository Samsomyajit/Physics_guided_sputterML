import numpy as np, pandas as pd, seaborn as sns, matplotlib.pyplot as plt
from scipy.cluster.hierarchy import linkage, leaves_list

def clustered_corr_heatmaps_grid_pub(
    Cp: pd.DataFrame, Cs: pd.DataFrame,
    pearson_cmap="coolwarm",        # diverging, centered at 0
    spearman_cmap="RdBu",           # diverging, centered at 0
    xtilt=-55,
    tick_fs=24, label_fs=28, title_fs=34, annot_fs=20,
    linewidth=0.6, linecolor="white",
    cluster_method="average", cluster_metric="euclidean",
    mask_upper=True, annotate=True
):
    """
    Draw clustered triangular heatmaps for Pearson (left) and Spearman (right),
    with separate colormaps & colorbars and matched ordering.

    Cp, Cs: square correlation DataFrames with identical row/column labels.
    """
    # ---------- 1) Sanity & common order (cluster once on Pearson) ----------
    assert (Cp.index.tolist()==Cp.columns.tolist()) and (Cs.index.tolist()==Cs.columns.tolist()), \
        "Cp and Cs must be square with identical labels on rows/cols."
    labels = list(Cp.index)

    # cluster on Pearson (you can swap to np.abs(Cp) if you prefer grouping by |r|)
    Z = linkage(Cp.values, method=cluster_method, metric=cluster_metric)
    order = leaves_list(Z)
    lbl = [labels[i] for i in order]

    Cp_ord = pd.DataFrame(Cp.values[order][:, order], index=lbl, columns=lbl)
    Cs_ord = pd.DataFrame(Cs.values[order][:, order], index=lbl, columns=lbl)

    # triangular mask
    mask = np.triu(np.ones_like(Cp_ord, dtype=bool), k=1) if mask_upper else None

    # ---------- 2) Plot ----------
    vmin, vmax = -1.0, 1.0
    fig, axes = plt.subplots(1, 2, figsize=(26, 12))

    def _draw(ax, M, title, cmap):
        hm = sns.heatmap(
            M.round(2),
            ax=ax, cmap=cmap, vmin=vmin, vmax=vmax,
            square=True, mask=mask, cbar=False,
            annot=annotate, fmt=".2f",
            annot_kws={"size": annot_fs},
            linewidths=linewidth, linecolor=linecolor,
        )
        ax.set_title(title, fontsize=title_fs, pad=12)
        ax.set_xlabel("Variables", fontsize=label_fs)
        ax.set_ylabel("Variables", fontsize=label_fs)

        # bottom ticks only, tilted
        ax.tick_params(top=False, bottom=True, labeltop=False, labelbottom=True)
        ax.set_xticklabels(
            ax.get_xticklabels(),
            rotation=xtilt,
            ha=("left" if xtilt < 0 else "right"),
            rotation_mode="anchor",
            fontsize=tick_fs
        )
        ax.set_yticklabels(ax.get_yticklabels(), rotation=0, fontsize=tick_fs)

        # improve annotation contrast cell-by-cell
        A = M.values
        for t in ax.texts:
            r, c = [int(v) for v in t.get_position()]
            val = A[r, c]
            t.set_color("white" if abs(val) >= 0.6 else "black")

        # individual colorbar for this panel
        cb = fig.colorbar(hm.collections[0], ax=ax, location="right",
                          fraction=0.046, pad=0.035)
        cb.set_label("Correlation Coefficient", fontsize=label_fs)
        for yt in cb.ax.get_yticklabels():
            yt.set_fontsize(tick_fs)

    _draw(axes[0], Cp_ord, "Pearson r", pearson_cmap)
    _draw(axes[1], Cs_ord, "Spearman ρ", spearman_cmap)

    plt.subplots_adjust(left=0.06, right=0.94, top=0.90, bottom=0.22, wspace=0.28)
    plt.show()
    return lbl, Cp_ord, Cs_ord  # handy if you want the clustered order back

