def simplex_project(x, s, lo, hi):
    x = np.minimum(np.maximum(x, lo), hi)
    s0 = x.sum()
    if s0 <= 0:
        return np.full_like(x, s/len(x))
    return x * (s / s0)

def quant_bounds(s, ql=0.01, qh=0.99):
    lo, hi = float(s.quantile(ql)), float(s.quantile(qh))
    if math.isclose(lo, hi):
        lo, hi = float(s.min()), float(s.max())
    return lo, hi

def pso_minimize(pred_fn, comp_lows, comp_highs, sum_target,
                 proc_lows=None, proc_highs=None,
                 n_particles=24, iters=80, rs=42):
    rng = np.random.default_rng(rs)
    dim_c = len(comp_lows)
    dim_p = 0 if proc_lows is None else len(proc_lows)

    pos_c, pos_p, vel_c, vel_p = [], [], [], []
    for _ in range(n_particles):
        pc = rng.uniform(comp_lows, comp_highs)
        pc = simplex_project(pc, s=sum_target, lo=comp_lows, hi=comp_highs)
        pos_c.append(pc); vel_c.append(np.zeros(dim_c))
        if dim_p>0:
            pp = rng.uniform(proc_lows, proc_highs)
            pos_p.append(pp); vel_p.append(np.zeros(dim_p))
    pos_c = np.array(pos_c); vel_c = np.array(vel_c)
    if dim_p>0:
        pos_p = np.array(pos_p); vel_p = np.array(vel_p)
    else:
        pos_p = np.zeros((len(pos_c),0)); vel_p = np.zeros((len(pos_c),0))

    def eval_i(i):
        return pred_fn(pos_c[i], pos_p[i] if dim_p>0 else None)

    pbest_c = pos_c.copy(); pbest_p = pos_p.copy()
    pbest_val = np.array([eval_i(i) for i in range(len(pos_c))])
    gbest_idx = int(np.argmin(pbest_val))
    gbest_c = pbest_c[gbest_idx].copy(); gbest_p = pbest_p[gbest_idx].copy()
    gbest_val = pbest_val[gbest_idx]
    w,c1,c2 = 0.62, 1.8, 1.8

    for _ in range(iters):
        r1c = rng.random(size=pos_c.shape); r2c = rng.random(size=pos_c.shape)
        vel_c = w*vel_c + c1*r1c*(pbest_c - pos_c) + c2*r2c*(gbest_c - pos_c)
        pos_c = pos_c + vel_c
        pos_c = np.minimum(np.maximum(pos_c, comp_lows), comp_highs)
        sums = pos_c.sum(axis=1, keepdims=True)
        pos_c = pos_c * (sum_target/np.clip(sums,1e-9,None))

        if dim_p>0:
            r1p = rng.random(size=pos_p.shape); r2p = rng.random(size=pos_p.shape)
            vel_p = w*vel_p + c1*r1p*(pbest_p - pos_p) + c2*r2p*(gbest_p - pos_p)
            pos_p = pos_p + vel_p
            pos_p = np.minimum(np.maximum(pos_p, proc_lows), proc_highs)

        vals = np.array([pred_fn(iC, iP if dim_p>0 else None) for iC,iP in zip(pos_c,pos_p)])
        improved = vals < pbest_val
        pbest_c[improved] = pos_c[improved]
        pbest_p[improved] = pos_p[improved]
        pbest_val[improved] = vals[improved]
        gidx = int(np.argmin(pbest_val))
        if pbest_val[gidx] < gbest_val:
            gbest_val = pbest_val[gidx]
            gbest_c = pbest_c[gidx].copy()
            gbest_p = pbest_p[gidx].copy()

    return (gbest_c, gbest_p if dim_p>0 else None, gbest_val)

