def add_header(img_path, title, subtitle="", label=None):
    """Add a journal-style header band (title/subtitle/label) to an image."""
    img = Image.open(img_path).convert("RGB")
    w, h = img.size
    header_h = 90
    canvas = Image.new("RGB", (w, h + header_h), "white")
    draw = ImageDraw.Draw(canvas)

    # fonts (fallback to default if DejaVuSans not available)
    try:
        ft = ImageFont.truetype("DejaVuSans.ttf", 32)
        fs = ImageFont.truetype("DejaVuSans.ttf", 22)
        fl = ImageFont.truetype("DejaVuSans.ttf", 28)
    except Exception:
        ft = fs = fl = ImageFont.load_default()

    if label:
        draw.text((16, 20), f"({label})", fill="black", font=fl)
    draw.text((90, 14), str(title), fill="black", font=ft)
    if subtitle:
        draw.text((90, 50), str(subtitle), fill="black", font=fs)

    canvas.paste(img, (0, header_h))
    return canvas

def hstack(paths, out_path, labels=None, titles=None, subtitles=None, gutter=24):
    """Horizontally stack images with headers; saves to out_path."""
    imgs = []
    for i, p in enumerate(paths):
        lab = None if labels is None else labels[i]
        tit = "" if titles is None else titles[i]
        sub = "" if subtitles is None else subtitles[i]
        imgs.append(add_header(p, tit, sub, lab))

    # resize to common height
    H = max(im.size[1] for im in imgs)
    resized = []
    for im in imgs:
        if im.size[1] != H:
            w = int(im.size[0] * (H / im.size[1]))
            resized.append(im.resize((w, H), Image.LANCZOS))
        else:
            resized.append(im)

    W = sum(im.size[0] for im in resized) + gutter * (len(resized) - 1)
    canvas = Image.new("RGB", (W, H), "white")

    x = 0
    for im in resized:
        canvas.paste(im, (x, 0))
        x += im.size[0] + gutter

    canvas.save(out_path, dpi=(600, 600))
    return out_path

