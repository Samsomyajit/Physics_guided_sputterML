def _fix_xgb_booster_attrs(booster):
    # Convert stray JSON-encoded attributes to scalars (seen in some 3.x boosters)
    try:
        attrs = booster.attributes()
        for key in ["base_score", "best_score", "global_bias"]:
            val = attrs.get(key)
            if isinstance(val, str) and val.startswith("[") and val.endswith("]"):
                try:
                    arr = json.loads(val.replace("E","e"))
                    if isinstance(arr, list) and arr:
                        booster.set_attr(**{key: str(float(arr[0]))})
                except Exception:
                    inner = val.strip("[]").replace("E","e")
                    try:
                        booster.set_attr(**{key: str(float(inner.split(",")[0]))})
                    except Exception:
                        pass
    except Exception:
        pass
    return booster

def tree_shap_explain_safe(trained_xgb_model, X_transformed, feature_names,
                           seed=42, max_points=2000):
    X = np.asarray(X_transformed, dtype=float)
    booster = getattr(trained_xgb_model, "get_booster", lambda: None)()
    # Preferred: new Tree explainer
    if booster is not None:
        booster = _fix_xgb_booster_attrs(booster)
        try:
            expl = shap.explainers.Tree(booster)
            exp = expl(X)
            if exp.shape[0] > max_points:
                exp = shap.sample(exp, max_points, random_state=seed)
            return exp
        except Exception:
            pass
        # Fallback classic
        try:
            te = shap.TreeExplainer(booster)
            sv = te.shap_values(X); base = te.expected_value
            if np.ndim(base)==0: base_vals = np.full(X.shape[0], float(base))
            else: base_vals = np.full(X.shape[0], float(np.array(base).ravel()[0]))
            exp = shap.Explanation(values=sv, base_values=base_vals, data=X,
                                   feature_names=list(feature_names))
            if exp.shape[0] > max_points:
                exp = shap.sample(exp, max_points, random_state=seed)
            return exp
        except Exception:
            pass
    # Last resort: permutation
    bg = shap.sample(X, min(300, X.shape[0]), random_state=seed)
    expl = shap.Explainer(trained_xgb_model.predict, bg, algorithm="permutation")
    exp = expl(X)
    if exp.shape[0] > max_points:
        exp = shap.sample(exp, max_points, random_state=seed)
    return exp

