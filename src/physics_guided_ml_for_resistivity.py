def _fix_xgb_booster_attrs(booster):
    try:
        attrs = booster.attributes()
        for key in ("base_score", "best_score", "global_bias"):
            val = attrs.get(key)
            if isinstance(val, str) and val.startswith("[") and val.endswith("]"):
                try:
                    import json
                    arr = json.loads(val.replace("E","e"))
                    if isinstance(arr, list) and arr:
                        booster.set_attr(**{key: str(float(arr[0]))})
                except Exception:
                    pass
    except Exception:
        pass
    return booster

def build_shap_explanation(model, X, feature_names, max_points=4000, seed=42):
    """
    Try Tree -> TreeExplainer -> Permutation (works for XGB 3.x, LGBM, CatBoost).
    Returns a shap.Explanation with correct feature_names.
    """
    X = np.asarray(X, dtype=float)
    exp = None

    # XGBoost booster if present (for best compatibility)
    booster = getattr(model, "get_booster", lambda: None)()
    if booster is not None:
        _fix_xgb_booster_attrs(booster)
        try:
            exp = shap.explainers.Tree(booster)(X)
        except Exception:
            try:
                te = shap.TreeExplainer(booster)
                sv = te.shap_values(X)
                base = te.expected_value
                if np.ndim(base)==0:
                    base_vals = np.full(X.shape[0], float(base))
                else:
                    base_vals = np.full(X.shape[0], float(np.array(base).ravel()[0]))
                exp = shap.Explanation(values=sv, base_values=base_vals, data=X,
                                       feature_names=list(feature_names))
            except Exception:
                exp = None

    # Generic tree models (LightGBM/CatBoost) via TreeExplainer
    if exp is None:
        try:
            te = shap.TreeExplainer(model)
            sv = te.shap_values(X)
            base = te.expected_value
            if np.ndim(base)==0:
                base_vals = np.full(X.shape[0], float(base))
            else:
                base_vals = np.full(X.shape[0], float(np.array(base).ravel()[0]))
            exp = shap.Explanation(values=sv, base_values=base_vals, data=X,
                                   feature_names=list(feature_names))
        except Exception:
            exp = None

    # Last resort: permutation
    if exp is None:
        bg = shap.sample(X, min(300, X.shape[0]), random_state=seed)
        expl = shap.Explainer(lambda A: model.predict(A), bg, algorithm="permutation")
        exp = expl(X)

    # set names if missing
    if not getattr(exp, "feature_names", None):
        exp.feature_names = list(feature_names)

    # downsample points for speed/clarity
    if exp.shape[0] > max_points:
        exp = shap.sample(exp, max_points, random_state=seed)
    return exp

