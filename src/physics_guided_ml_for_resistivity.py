from numpy.random import default_rng
rng_global = default_rng(123)

def fit_copula(X):
    """Gaussian copula via rank-Gaussian transform."""
    qt = QuantileTransformer(n_quantiles=min(100, len(X)),
                             output_distribution="normal", random_state=42)
    Z  = qt.fit_transform(X)
    mu = Z.mean(0)
    cov = np.cov(Z.T) + 1e-6*np.eye(Z.shape[1])
    return qt, mu, cov

def sample_copula(qt, mu, cov, n):
    Zs = rng_global.multivariate_normal(mu, cov, size=n)
    return qt.inverse_transform(Zs)

def enforce_constraints(Xs):
    Xs = np.clip(Xs, mins, maxs)
    if ELEMENTS:
        idx = [X_full.columns.get_loc(c) for c in ELEMENTS]
        s = Xs[:, idx].sum(1, keepdims=True) + 1e-12
        tgt = 100.0 if 80 <= np.median(s) <= 120 else 1.0
        Xs[:, idx] *= (tgt / s)
    for c in INTISH:
        j = X_full.columns.get_loc(c); Xs[:, j] = np.round(Xs[:, j])
    return Xs

def local_residual_noise(X_tr, y_tr, k=7):
    """Return function ~ N(0, sigma_kNN(x)) for heteroscedastic noise."""
    teacher = make_xgb(seed=42, n_estimators=800)
    teacher.fit(X_tr, y_tr)
    res = y_tr - teacher.predict(X_tr)
    if len(X_tr) < 3:
        sig = float(np.std(res))
        def draw(_): return rng_global.normal(0.0, sig)
        return draw
    sc  = StandardScaler().fit(X_tr)
    Z   = sc.transform(X_tr)
    k   = max(1, min(k, len(Z)-1))
    knn = KNeighborsRegressor(n_neighbors=k, weights="distance").fit(Z, res**2 + 1e-8)
    def draw(x_new):
        v = float(knn.predict(sc.transform(x_new.reshape(1,-1)))[0])
        return rng_global.normal(0.0, np.sqrt(max(v, 1e-8)))
    return draw

def augment_train(X_tr, y_tr, mult=2.0, by_cluster=True):
    """Gaussian-copula sampling + constraint repair + local noise."""
    n_syn = max(1, int(np.ceil(len(X_tr) * mult)))
    Xsyn = None

    if by_cluster and len(X_tr) >= 30:
        sc  = StandardScaler().fit(X_tr)
        Z   = sc.transform(X_tr)
        k   = min(3, max(2, len(X_tr)//25))
        gmm = GaussianMixture(n_components=k, covariance_type="full", random_state=42).fit(Z)
        lab = gmm.predict(Z)
        blocks = []
        for L in range(k):
            idx = np.where(lab == L)[0]
            if len(idx) < 8:  # skip tiny clusters
                continue
            qt, mu, cov = fit_copula(X_tr[idx])
            nL = max(1, int(np.ceil(n_syn * len(idx) / len(X_tr))))
            blocks.append(sample_copula(qt, mu, cov, nL))
        if blocks:
            Xsyn = np.vstack(blocks)

    # IMPORTANT: explicit None/size check (never "if not Xsyn:")
    if Xsyn is None or Xsyn.size == 0:
        qt, mu, cov = fit_copula(X_tr)
        Xsyn = sample_copula(qt, mu, cov, n_syn)

    Xsyn = enforce_constraints(Xsyn)

    # label with teacher + add heteroscedastic residual noise
    teacher = make_xgb(seed=123, n_estimators=1200, max_depth=7)
    teacher.fit(X_tr, y_tr)
    y_hat = teacher.predict(Xsyn)

    draw_noise = local_residual_noise(X_tr, y_tr, k=7)
    y_noisy = y_hat + np.array([draw_noise(x) for x in Xsyn])

    return np.vstack([X_tr, Xsyn]), np.hstack([y_tr, y_noisy])

def cluster_then_model(X_tr, y_tr, X_te):
    """Regime models with GMM gating; falls back to single model when clusters are weak."""
    if len(X_tr) < 12:
        mdl = make_xgb(seed=7); mdl.fit(X_tr, y_tr); return mdl.predict(X_te)

    sc  = StandardScaler().fit(X_tr); Z = sc.transform(X_tr)
    k   = min(3, max(2, len(X_tr)//25))
    gmm = GaussianMixture(n_components=k, covariance_type="full", random_state=7).fit(Z)
    lab = gmm.predict(Z)

    # fall back if any cluster too small
    if len(np.unique(lab)) < 2 or any((lab == L).sum() < 5 for L in range(k)):
        mdl = make_xgb(seed=7); mdl.fit(X_tr, y_tr); return mdl.predict(X_te)

    models = []
    for L in range(k):
        idx = np.where(lab == L)[0]
        mdl = make_xgb(seed=7); mdl.fit(X_tr[idx], y_tr[idx])
        models.append(mdl)

    Zte = sc.transform(X_te); lab_te = gmm.predict(Zte)
    preds = np.zeros(len(X_te))
    for L in range(k):
        j = np.where(lab_te == L)[0]
        if len(j): preds[j] = models[L].predict(X_te[j])
    return preds

