def conformal_coverage_report(X, y_raw, t_modeB="log10", outer_splits=OUTER_K, alpha=0.05, seed=SEED_MAIN+10):
    outer = KFold(outer_splits, shuffle=True, random_state=seed)
    frames=[]
    for k,(tr,te) in enumerate(outer.split(X, y_raw), 1):
        # inner split for calibration
        inner_split = list(KFold(5, shuffle=True, random_state=seed+k).split(tr))[0]
        fit_idx = np.array(tr)[inner_split[0]]
        cal_idx = np.array(tr)[inner_split[1]]

        y_fit_t = np.log10(y_raw[fit_idx]) if t_modeB=="log10" else y_raw[fit_idx]
        y_cal   = y_raw[cal_idx]; y_te = y_raw[te]

        s = make_search(seed+k)
        s.fit(X.iloc[fit_idx], y_fit_t)
        # predictions
        p_cal_t = s.predict(X.iloc[cal_idx])
        p_te_t  = s.predict(X.iloc[te])

        if t_modeB=="log10":
            e = y_fit_t - s.predict(X.iloc[fit_idx])
            smear = float(np.mean(10**e))
            y_cal_hat = (10**p_cal_t) * smear
            y_te_hat  = (10**p_te_t)  * smear
        else:
            y_cal_hat = p_cal_t; y_te_hat = p_te_t

        resid = np.abs(y_cal - y_cal_hat)
        q = np.quantile(resid, 1 - alpha, method="higher")
        lower = y_te_hat - q
        upper = y_te_hat + q
        frames.append(pd.DataFrame({
            "fold":k, "y":y_te, "y_hat":y_te_hat, "L":lower, "U":upper,
            "covered":(y_te>=lower)&(y_te<=upper), "len":upper-lower
        }))
    df = pd.concat(frames, ignore_index=True)
    return df

